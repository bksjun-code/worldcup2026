def update():
    db = SessionLocal()
    matches = db.query(Match).filter(Match.stage == MatchStage.GROUP).all()

    updated = 0
    matched_keys = set()
    for m in matches:
        key_found = None
        for group, teams, new_dt in NEW_SCHEDULE:
            if m.group_name == group and {m.home_team, m.away_team} == teams:
                key_found = (group, frozenset(teams))
                m.match_date = new_dt
                updated += 1
                break
        if key_found:
            matched_keys.add(key_found)
        else:
            print(f"매칭 실패: {m.group_name}조 {m.home_team} vs {m.away_team}")

    db.commit()
    db.close()

    print(f"업데이트 완료: {updated}건 / 전체 {len(matches)}건")
    if len(matched_keys) != len(NEW_SCHEDULE):
        print(f"경고: NEW_SCHEDULE {len(NEW_SCHEDULE)}건 중 {len(matched_keys)}건만 매칭됨")


if __name__ == "__main__":
    update()
